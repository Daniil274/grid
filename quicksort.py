def quicksort(arr):
    """
    Реализация алгоритма быстрой сортировки (QuickSort).
    
    Алгоритм:
    1. Выбираем опорный элемент (pivot) - в данной реализации это последний элемент
    2. Разделяем список на три части:
       - элементы меньше опорного
       - элементы равные опорному  
       - элементы больше опорного
    3. Рекурсивно сортируем части "меньше" и "больше"
    4. Объединяем три части в отсортированный список
    
    Временная сложность:
    - В среднем случае: O(n log n)
    - В худшем случае: O(n²) - когда опорный элемент всегда минимальный или максимальный
    - В лучшем случае: O(n log n)
    
    Пространственная сложность: O(log n) из-за рекурсивных вызовов
    
    Args:
        arr (list): Список чисел для сортировки
        
    Returns:
        list: Отсортированный список чисел
    """
    # Базовый случай рекурсии: если список пустой или содержит один элемент
    if len(arr) <= 1:
        return arr
    
    # Выбираем опорный элемент (pivot) - последний элемент списка
    pivot = arr[-1]
    
    # Разделяем список на три части
    less = []      # элементы меньше опорного
    equal = []     # элементы равные опорному
    greater = []   # элементы больше опорного
    
    for num in arr:
        if num < pivot:
            less.append(num)
        elif num == pivot:
            equal.append(num)
        else:
            greater.append(num)
    
    # Рекурсивно сортируем части "меньше" и "больше"
    # и объединяем с равными элементами
    return quicksort(less) + equal + quicksort(greater)


def quicksort_inplace(arr, low=0, high=None):
    """
    Реализация быстрой сортировки с сортировкой на месте (in-place).
    Эта версия модифицирует исходный список и не создает новых списков.
    
    Args:
        arr (list): Список чисел для сортировки
        low (int): Начальный индекс диапазона для сортировки
        high (int): Конечный индекс диапазона для сортировки
        
    Returns:
        list: Отсортированный список (исходный список модифицируется)
    """
    if high is None:
        high = len(arr) - 1
    
    if low < high:
        # Разделяем список и получаем индекс опорного элемента
        pi = partition(arr, low, high)
        
        # Рекурсивно сортируем элементы до и после опорного
        quicksort_inplace(arr, low, pi - 1)
        quicksort_inplace(arr, pi + 1, high)
    
    return arr


def partition(arr, low, high):
    """
    Вспомогательная функция для разделения списка.
    Выбирает опорный элемент и размещает все меньшие элементы слева,
    а все большие элементы справа от опорного.
    
    Args:
        arr (list): Список чисел
        low (int): Начальный индекс диапазона
        high (int): Конечный индекс диапазона
        
    Returns:
        int: Индекс опорного элемента после разделения
    """
    # Выбираем опорный элемент (последний элемент диапазона)
    pivot = arr[high]
    
    # Индекс для размещения элементов меньших чем опорный
    i = low - 1
    
    # Проходим по всем элементам от low до high-1
    for j in range(low, high):
        # Если текущий элемент меньше или равен опорному
        if arr[j] <= pivot:
            i += 1
            # Меняем местами arr[i] и arr[j]
            arr[i], arr[j] = arr[j], arr[i]
    
    # Помещаем опорный элемент на правильную позицию
    arr[i + 1], arr[high] = arr[high], arr[i + 1]
    
    return i + 1


